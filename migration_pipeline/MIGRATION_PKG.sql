-- DeltaMax Migration PL/SQL package
-- Run oracle_schema.sql first, then run this entire file in SQL Developer using F5.
-- Connect as the schema that owns MIGR_RUNS, MIGR_CONTROL, MIGR_FILES, MIGR_ROWS and MIGR_LOG.

CREATE OR REPLACE PACKAGE MIGRATION_PKG AS
    PROCEDURE START_MIGRATION(
        P_DETAILS IN VARCHAR2 DEFAULT 'Migration pipeline started',
        P_RUN_ID OUT VARCHAR2
    );

    PROCEDURE LOG_STEP(
        P_RUN_ID IN VARCHAR2,
        P_STEP_NAME IN VARCHAR2,
        P_STATUS IN VARCHAR2,
        P_RECORD_COUNT IN NUMBER DEFAULT NULL,
        P_DETAILS IN VARCHAR2 DEFAULT NULL
    );

    PROCEDURE FINISH_MIGRATION(
        P_RUN_ID IN VARCHAR2,
        P_STATUS IN VARCHAR2 DEFAULT 'SUCCESS',
        P_DETAILS IN VARCHAR2 DEFAULT 'Migration pipeline completed'
    );

    PROCEDURE VALIDATE_STAGE(
        P_RUN_ID IN VARCHAR2,
        P_FILE_KEY IN VARCHAR2,
        P_ACTUAL_COUNT OUT NUMBER,
        P_EXPECTED_COUNT OUT NUMBER,
        P_STATUS OUT VARCHAR2
    );

    PROCEDURE COPY_STAGE(
        P_RUN_ID IN VARCHAR2,
        P_SOURCE_FILE_KEY IN VARCHAR2,
        P_TARGET_FILE_KEY IN VARCHAR2
    );
END MIGRATION_PKG;
/

CREATE OR REPLACE PACKAGE BODY MIGRATION_PKG AS
    PROCEDURE START_MIGRATION(
        P_DETAILS IN VARCHAR2,
        P_RUN_ID OUT VARCHAR2
    ) IS
    BEGIN
        P_RUN_ID := RAWTOHEX(SYS_GUID());

        INSERT INTO MIGR_RUNS (RUN_ID, STATUS, DETAILS)
        VALUES (P_RUN_ID, 'RUNNING', SUBSTR(P_DETAILS, 1, 2000));

        MERGE INTO MIGR_CONTROL C
        USING (SELECT 'ACTIVE' AS CONTROL_KEY FROM DUAL) S
        ON (C.CONTROL_KEY = S.CONTROL_KEY)
        WHEN MATCHED THEN UPDATE SET C.RUN_ID = P_RUN_ID
        WHEN NOT MATCHED THEN
            INSERT (CONTROL_KEY, RUN_ID) VALUES ('ACTIVE', P_RUN_ID);

        INSERT INTO MIGR_LOG (RUN_ID, STEP_NAME, STATUS, RECORD_COUNT, DETAILS)
        VALUES (P_RUN_ID, 'START', 'SUCCESS', 0, SUBSTR(P_DETAILS, 1, 2000));

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END START_MIGRATION;

    PROCEDURE LOG_STEP(
        P_RUN_ID IN VARCHAR2,
        P_STEP_NAME IN VARCHAR2,
        P_STATUS IN VARCHAR2,
        P_RECORD_COUNT IN NUMBER,
        P_DETAILS IN VARCHAR2
    ) IS
        V_RUN_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_RUN_COUNT
        FROM MIGR_RUNS
        WHERE RUN_ID = P_RUN_ID;

        IF V_RUN_COUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Migration RUN_ID does not exist: ' || P_RUN_ID);
        END IF;

        INSERT INTO MIGR_LOG (RUN_ID, STEP_NAME, STATUS, RECORD_COUNT, DETAILS)
        VALUES (P_RUN_ID, SUBSTR(P_STEP_NAME, 1, 100), SUBSTR(UPPER(P_STATUS), 1, 20),
                P_RECORD_COUNT, SUBSTR(P_DETAILS, 1, 2000));
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END LOG_STEP;

    PROCEDURE FINISH_MIGRATION(
        P_RUN_ID IN VARCHAR2,
        P_STATUS IN VARCHAR2,
        P_DETAILS IN VARCHAR2
    ) IS
        V_STATUS VARCHAR2(20);
    BEGIN
        V_STATUS := UPPER(P_STATUS);
        IF V_STATUS NOT IN ('SUCCESS', 'FAILED', 'RUNNING') THEN
            RAISE_APPLICATION_ERROR(-20002, 'Status must be SUCCESS, FAILED, or RUNNING.');
        END IF;

        UPDATE MIGR_RUNS
        SET STATUS = V_STATUS,
            FINISHED_AT = CASE WHEN V_STATUS = 'RUNNING' THEN NULL ELSE SYSTIMESTAMP END,
            DETAILS = SUBSTR(P_DETAILS, 1, 2000)
        WHERE RUN_ID = P_RUN_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Migration RUN_ID does not exist: ' || P_RUN_ID);
        END IF;

        INSERT INTO MIGR_LOG (RUN_ID, STEP_NAME, STATUS, DETAILS)
        VALUES (P_RUN_ID, 'FINISH', V_STATUS, SUBSTR(P_DETAILS, 1, 2000));
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END FINISH_MIGRATION;

    PROCEDURE VALIDATE_STAGE(
        P_RUN_ID IN VARCHAR2,
        P_FILE_KEY IN VARCHAR2,
        P_ACTUAL_COUNT OUT NUMBER,
        P_EXPECTED_COUNT OUT NUMBER,
        P_STATUS OUT VARCHAR2
    ) IS
    BEGIN
        SELECT ROW_COUNT INTO P_EXPECTED_COUNT
        FROM MIGR_FILES
        WHERE RUN_ID = P_RUN_ID AND FILE_KEY = P_FILE_KEY;

        SELECT COUNT(*) INTO P_ACTUAL_COUNT
        FROM MIGR_ROWS
        WHERE RUN_ID = P_RUN_ID AND FILE_KEY = P_FILE_KEY;

        IF P_ACTUAL_COUNT = P_EXPECTED_COUNT THEN
            P_STATUS := 'SUCCESS';
        ELSE
            P_STATUS := 'FAILED';
        END IF;

        INSERT INTO MIGR_LOG (RUN_ID, STEP_NAME, STATUS, RECORD_COUNT, DETAILS)
        VALUES (P_RUN_ID, 'VALIDATE:' || SUBSTR(P_FILE_KEY, 1, 85), P_STATUS,
                P_ACTUAL_COUNT,
                'Expected rows=' || P_EXPECTED_COUNT || '; actual rows=' || P_ACTUAL_COUNT);
        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20004, 'Stage not found for RUN_ID=' || P_RUN_ID || ', FILE_KEY=' || P_FILE_KEY);
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END VALIDATE_STAGE;

    PROCEDURE COPY_STAGE(
        P_RUN_ID IN VARCHAR2,
        P_SOURCE_FILE_KEY IN VARCHAR2,
        P_TARGET_FILE_KEY IN VARCHAR2
    ) IS
        V_COLUMNS_JSON CLOB;
        V_ROW_COUNT NUMBER;
        V_SOURCE_COUNT NUMBER;
    BEGIN
        IF P_SOURCE_FILE_KEY = P_TARGET_FILE_KEY THEN
            RAISE_APPLICATION_ERROR(-20005, 'Source and target stage names must be different.');
        END IF;

        SELECT COLUMNS_JSON, ROW_COUNT
        INTO V_COLUMNS_JSON, V_ROW_COUNT
        FROM MIGR_FILES
        WHERE RUN_ID = P_RUN_ID AND FILE_KEY = P_SOURCE_FILE_KEY;

        DELETE FROM MIGR_ROWS
        WHERE RUN_ID = P_RUN_ID AND FILE_KEY = P_TARGET_FILE_KEY;

        DELETE FROM MIGR_FILES
        WHERE RUN_ID = P_RUN_ID AND FILE_KEY = P_TARGET_FILE_KEY;

        INSERT INTO MIGR_FILES (RUN_ID, FILE_KEY, COLUMNS_JSON, ROW_COUNT, UPDATED_AT)
        VALUES (P_RUN_ID, SUBSTR(P_TARGET_FILE_KEY, 1, 250), V_COLUMNS_JSON, V_ROW_COUNT, SYSTIMESTAMP);

        INSERT INTO MIGR_ROWS (RUN_ID, FILE_KEY, ROW_NUM, PAYLOAD)
        SELECT RUN_ID, SUBSTR(P_TARGET_FILE_KEY, 1, 250), ROW_NUM, PAYLOAD
        FROM MIGR_ROWS
        WHERE RUN_ID = P_RUN_ID AND FILE_KEY = P_SOURCE_FILE_KEY;

        SELECT COUNT(*) INTO V_SOURCE_COUNT
        FROM MIGR_ROWS
        WHERE RUN_ID = P_RUN_ID AND FILE_KEY = P_SOURCE_FILE_KEY;

        INSERT INTO MIGR_LOG (RUN_ID, STEP_NAME, STATUS, RECORD_COUNT, DETAILS)
        VALUES (P_RUN_ID, 'COPY_STAGE',
                CASE WHEN V_SOURCE_COUNT = V_ROW_COUNT THEN 'SUCCESS' ELSE 'FAILED' END,
                V_SOURCE_COUNT,
                'Copied ' || P_SOURCE_FILE_KEY || ' to ' || P_TARGET_FILE_KEY ||
                '; expected rows=' || V_ROW_COUNT || '; copied rows=' || V_SOURCE_COUNT);

        IF V_SOURCE_COUNT <> V_ROW_COUNT THEN
            RAISE_APPLICATION_ERROR(-20006, 'Copied row count does not match source metadata.');
        END IF;
        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20007, 'Source stage not found: ' || P_SOURCE_FILE_KEY);
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END COPY_STAGE;
END MIGRATION_PKG;
