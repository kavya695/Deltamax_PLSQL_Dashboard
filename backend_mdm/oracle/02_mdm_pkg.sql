-- Oracle-side helper package. Python trust engine writes score detail; this package validates and summarizes stored results.
CREATE OR REPLACE PACKAGE MDM_PKG AS
  PROCEDURE VALIDATE_DATA;
  PROCEDURE REFRESH_GOLDEN_RECORDS;
  PROCEDURE PROCESS_STATUS;
END MDM_PKG;
/
CREATE OR REPLACE PACKAGE BODY MDM_PKG AS
  PROCEDURE VALIDATE_DATA IS
    v_count NUMBER;
    v_error VARCHAR2(1000);
  BEGIN
    SELECT COUNT(*) INTO v_count FROM MDM_CUSTOMER_STG;
    INSERT INTO MDM_RUN_LOG (RUN_ID, STEP_NAME, STATUS, RECORD_COUNT, DETAILS)
    VALUES (SYS_GUID(), 'VALIDATE', 'SUCCESS', v_count, 'Staging table accessible; record count checked by PL/SQL');
    COMMIT;
  EXCEPTION WHEN OTHERS THEN
    v_error := SQLERRM;
    INSERT INTO MDM_RUN_LOG (RUN_ID, STEP_NAME, STATUS, DETAILS)
    VALUES (SYS_GUID(), 'VALIDATE', 'FAILED', v_error);
    COMMIT;
    RAISE;
  END VALIDATE_DATA;

  PROCEDURE REFRESH_GOLDEN_RECORDS IS
    v_count NUMBER;
  BEGIN
    DELETE FROM MDM_CUSTOMER_GOLDEN;
    INSERT INTO MDM_CUSTOMER_GOLDEN (CLUSTER_ID,RECORD_ID,SOURCE_SYSTEM,FIRST_NAME,LAST_NAME,EMAIL,PHONE,DATE_OF_BIRTH,GENDER,ADDRESS_LINE1,CITY,STATE,POSTAL_CODE,COUNTRY,LOYALTY_TIER,CUSTOMER_SINCE,LAST_PURCHASE_DATE,TOTAL_LIFETIME_VALUE,IS_ACTIVE,CREATED_AT,UPDATED_AT,TRUST_SCORE,SURVIVORSHIP_REASON,CREATED_ON)
    SELECT CLUSTER_ID,RECORD_ID,SOURCE_SYSTEM,FIRST_NAME,LAST_NAME,EMAIL,PHONE,DATE_OF_BIRTH,GENDER,ADDRESS_LINE1,CITY,STATE,POSTAL_CODE,COUNTRY,LOYALTY_TIER,CUSTOMER_SINCE,LAST_PURCHASE_DATE,TOTAL_LIFETIME_VALUE,IS_ACTIVE,CREATED_AT,UPDATED_AT,TRUST_SCORE,'Highest trust score in cluster',SYSTIMESTAMP
    FROM (SELECT s.*, sc.TRUST_SCORE, ROW_NUMBER() OVER (PARTITION BY s.CLUSTER_ID ORDER BY sc.TRUST_SCORE DESC, s.RECORD_ID) rn FROM MDM_CUSTOMER_STG s JOIN MDM_CUSTOMER_SCORES sc ON sc.RECORD_ID=s.RECORD_ID)
    WHERE rn=1;
    v_count := SQL%ROWCOUNT;
    INSERT INTO MDM_RUN_LOG (RUN_ID,STEP_NAME,STATUS,RECORD_COUNT,DETAILS)
    VALUES (SYS_GUID(),'GOLDEN','SUCCESS',v_count,'Golden records refreshed by PL/SQL');
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END REFRESH_GOLDEN_RECORDS;

  PROCEDURE PROCESS_STATUS IS
    v_raw NUMBER; v_scored NUMBER; v_golden NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_raw FROM MDM_CUSTOMER_STG;
    SELECT COUNT(*) INTO v_scored FROM MDM_CUSTOMER_SCORES;
    SELECT COUNT(*) INTO v_golden FROM MDM_CUSTOMER_GOLDEN;
    INSERT INTO MDM_RUN_LOG (RUN_ID,STEP_NAME,STATUS,RECORD_COUNT,DETAILS)
    VALUES (SYS_GUID(),'STATUS','SUCCESS',v_raw,'staging='||v_raw||', scored='||v_scored||', golden='||v_golden);
    COMMIT;
  END PROCESS_STATUS;
END MDM_PKG;
/
