-- Run as MDM schema owner in SQL Developer.
SELECT USER FROM DUAL;
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE 'MDM_%' ORDER BY TABLE_NAME;
SELECT COUNT(*) AS RAW_RECORDS FROM MDM_CUSTOMER_STG;
SELECT COUNT(*) AS SCORED_RECORDS FROM MDM_CUSTOMER_SCORES;
SELECT COUNT(*) AS GOLDEN_RECORDS FROM MDM_CUSTOMER_GOLDEN;
SELECT SOURCE_SYSTEM, COUNT(*) AS RECORDS FROM MDM_CUSTOMER_STG GROUP BY SOURCE_SYSTEM ORDER BY SOURCE_SYSTEM;
SELECT ROUND(AVG(TRUST_SCORE),2) AS AVG_TRUST_SCORE, ROUND(MIN(TRUST_SCORE),2) AS MIN_TRUST_SCORE, ROUND(MAX(TRUST_SCORE),2) AS MAX_TRUST_SCORE FROM MDM_CUSTOMER_SCORES;
SELECT CLUSTER_ID, RECORD_ID, FIRST_NAME, LAST_NAME, EMAIL, TRUST_SCORE FROM MDM_CUSTOMER_GOLDEN ORDER BY CLUSTER_ID FETCH FIRST 20 ROWS ONLY;
SELECT * FROM MDM_RUN_LOG ORDER BY LOG_ID DESC FETCH FIRST 50 ROWS ONLY;
