
-- Run this entire file in SQL Developer as DELTAMAX_V5 (or a dedicated SECURITY schema).
-- Press F5 (Run Script). This creates Oracle storage and the SECURITY_PKG package.
CREATE TABLE SEC_RUNS (
  RUN_ID VARCHAR2(32) PRIMARY KEY,
  STATUS VARCHAR2(20) NOT NULL,
  STARTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP,
  DETAILS VARCHAR2(2000)
);
CREATE TABLE SEC_LOG (
  LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  RUN_ID VARCHAR2(32) NOT NULL REFERENCES SEC_RUNS(RUN_ID),
  STEP_NAME VARCHAR2(100) NOT NULL,
  STATUS VARCHAR2(20) NOT NULL,
  RECORD_COUNT NUMBER,
  DETAILS VARCHAR2(2000),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX SEC_LOG_RUN_IDX ON SEC_LOG(RUN_ID);
CREATE TABLE SEC_DATASETS (
  RUN_ID VARCHAR2(32) NOT NULL REFERENCES SEC_RUNS(RUN_ID),
  DATASET_KEY VARCHAR2(100) NOT NULL,
  ROW_COUNT NUMBER NOT NULL,
  COLUMNS_JSON CLOB,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT SEC_DATASETS_PK PRIMARY KEY (RUN_ID, DATASET_KEY)
);
CREATE TABLE SEC_ROWS (
  RUN_ID VARCHAR2(32) NOT NULL,
  DATASET_KEY VARCHAR2(100) NOT NULL,
  ROW_NUM NUMBER NOT NULL,
  RECORD_ID VARCHAR2(100),
  PAYLOAD CLOB NOT NULL,
  CONSTRAINT SEC_ROWS_PK PRIMARY KEY (RUN_ID, DATASET_KEY, ROW_NUM),
  CONSTRAINT SEC_ROWS_DATASET_FK FOREIGN KEY (RUN_ID, DATASET_KEY)
    REFERENCES SEC_DATASETS(RUN_ID, DATASET_KEY)
);
CREATE INDEX SEC_ROWS_RECORD_IDX ON SEC_ROWS(RUN_ID, RECORD_ID);
CREATE TABLE SEC_SUMMARY (
  RUN_ID VARCHAR2(32) PRIMARY KEY REFERENCES SEC_RUNS(RUN_ID),
  SUMMARY_JSON CLOB NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
/
CREATE OR REPLACE PACKAGE SECURITY_PKG AS
  PROCEDURE START_RUN(P_DETAILS IN VARCHAR2 DEFAULT 'Security pipeline started', P_RUN_ID OUT VARCHAR2);
  PROCEDURE LOG_STEP(P_RUN_ID IN VARCHAR2, P_STEP_NAME IN VARCHAR2, P_STATUS IN VARCHAR2,
                     P_RECORD_COUNT IN NUMBER DEFAULT NULL, P_DETAILS IN VARCHAR2 DEFAULT NULL);
  PROCEDURE FINISH_RUN(P_RUN_ID IN VARCHAR2, P_STATUS IN VARCHAR2 DEFAULT 'SUCCESS',
                       P_DETAILS IN VARCHAR2 DEFAULT 'Security pipeline completed');
END SECURITY_PKG;
/
CREATE OR REPLACE PACKAGE BODY SECURITY_PKG AS
  PROCEDURE START_RUN(P_DETAILS IN VARCHAR2, P_RUN_ID OUT VARCHAR2) IS
  BEGIN
    P_RUN_ID := RAWTOHEX(SYS_GUID());
    INSERT INTO SEC_RUNS(RUN_ID, STATUS, DETAILS) VALUES(P_RUN_ID, 'RUNNING', SUBSTR(P_DETAILS,1,2000));
    INSERT INTO SEC_LOG(RUN_ID, STEP_NAME, STATUS, RECORD_COUNT, DETAILS)
      VALUES(P_RUN_ID, 'START', 'SUCCESS', 0, SUBSTR(P_DETAILS,1,2000));
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END START_RUN;

  PROCEDURE LOG_STEP(P_RUN_ID IN VARCHAR2, P_STEP_NAME IN VARCHAR2, P_STATUS IN VARCHAR2,
                     P_RECORD_COUNT IN NUMBER, P_DETAILS IN VARCHAR2) IS
  BEGIN
    INSERT INTO SEC_LOG(RUN_ID, STEP_NAME, STATUS, RECORD_COUNT, DETAILS)
      VALUES(P_RUN_ID, SUBSTR(P_STEP_NAME,1,100), SUBSTR(UPPER(P_STATUS),1,20),
             P_RECORD_COUNT, SUBSTR(P_DETAILS,1,2000));
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END LOG_STEP;

  PROCEDURE FINISH_RUN(P_RUN_ID IN VARCHAR2, P_STATUS IN VARCHAR2, P_DETAILS IN VARCHAR2) IS
    V_STATUS VARCHAR2(20) := UPPER(P_STATUS);
  BEGIN
    IF V_STATUS NOT IN ('SUCCESS','FAILED','RUNNING') THEN
      RAISE_APPLICATION_ERROR(-20101, 'Status must be SUCCESS, FAILED, or RUNNING');
    END IF;
    UPDATE SEC_RUNS SET STATUS=V_STATUS,
      FINISHED_AT=CASE WHEN V_STATUS='RUNNING' THEN NULL ELSE SYSTIMESTAMP END,
      DETAILS=SUBSTR(P_DETAILS,1,2000)
      WHERE RUN_ID=P_RUN_ID;
    IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20102, 'Security RUN_ID not found'); END IF;
    INSERT INTO SEC_LOG(RUN_ID, STEP_NAME, STATUS, DETAILS)
      VALUES(P_RUN_ID, 'FINISH', V_STATUS, SUBSTR(P_DETAILS,1,2000));
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
  END FINISH_RUN;
END SECURITY_PKG;
