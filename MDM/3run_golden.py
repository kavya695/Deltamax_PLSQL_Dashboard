"""Build golden records from Oracle staging/scores and persist them in Oracle."""
from oracle_db import connect

def run():
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute("""INSERT INTO MDM_CUSTOMER_GOLDEN (CLUSTER_ID,RECORD_ID,SOURCE_SYSTEM,FIRST_NAME,LAST_NAME,EMAIL,PHONE,DATE_OF_BIRTH,GENDER,ADDRESS_LINE1,CITY,STATE,POSTAL_CODE,COUNTRY,LOYALTY_TIER,CUSTOMER_SINCE,LAST_PURCHASE_DATE,TOTAL_LIFETIME_VALUE,IS_ACTIVE,CREATED_AT,UPDATED_AT,TRUST_SCORE,SURVIVORSHIP_REASON,CREATED_ON)
SELECT CLUSTER_ID,RECORD_ID,SOURCE_SYSTEM,FIRST_NAME,LAST_NAME,EMAIL,PHONE,DATE_OF_BIRTH,GENDER,ADDRESS_LINE1,CITY,STATE,POSTAL_CODE,COUNTRY,LOYALTY_TIER,CUSTOMER_SINCE,LAST_PURCHASE_DATE,TOTAL_LIFETIME_VALUE,IS_ACTIVE,CREATED_AT,UPDATED_AT,TRUST_SCORE,'Highest trust score in cluster',SYSTIMESTAMP
FROM (SELECT s.*, sc.TRUST_SCORE, ROW_NUMBER() OVER (PARTITION BY s.CLUSTER_ID ORDER BY sc.TRUST_SCORE DESC, s.RECORD_ID) rn FROM MDM_CUSTOMER_STG s JOIN MDM_CUSTOMER_SCORES sc ON sc.RECORD_ID=s.RECORD_ID)
WHERE rn=1""")
            count=cur.rowcount
            cur.execute("INSERT INTO MDM_RUN_LOG (RUN_ID,STEP_NAME,STATUS,RECORD_COUNT,DETAILS) VALUES (SYS_GUID(),'GOLDEN','SUCCESS',:n,:d)", n=count, d='Golden record selected per cluster by highest trust score using Oracle SQL')
        conn.commit()
    print(f'Created {count} golden records in Oracle table MDM_CUSTOMER_GOLDEN.')
if __name__ == '__main__': run()
